"""Generate MySQL DDL (schema.sql) straight from the SQLAlchemy models - no DB needed."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from sqlalchemy.dialects import mysql
from sqlalchemy.schema import CreateIndex, CreateTable
from app import create_app, db

app = create_app("config.TestConfig")
out = ["-- MediCare HMS: MySQL 8 schema (generated by scripts/export_schema.py)",
       "CREATE DATABASE IF NOT EXISTS hospital_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;",
       "USE hospital_db;", ""]
with app.app_context():
    for t in db.metadata.sorted_tables:
        out.append(str(CreateTable(t).compile(dialect=mysql.dialect())).strip() + " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;\n")
        for ix in sorted(t.indexes, key=lambda i: i.name):
            out.append(str(CreateIndex(ix).compile(dialect=mysql.dialect())).strip() + ";")
        out.append("")
out += ["INSERT IGNORE INTO roles (name, description) VALUES",
        "  ('admin','Full system access'),('doctor','Clinical access to own patients'),",
        "  ('receptionist','Front desk: patients, appointments, billing');"]
path = pathlib.Path(__file__).resolve().parent.parent / "schema.sql"
path.write_text("\n".join(out) + "\n")
print("wrote", path)
